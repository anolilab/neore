/**
 * Generates services/llm-gateway/src/models.generated.ts from the AI package registry.
 *
 * Includes ALL model modes: text, image, video, speech-to-text, text-to-speech.
 * Excludes external/marketing-only models (provider: "external").
 *
 * Usage: node tools/generate-gateway-models.mjs
 */
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const { MODEL_REGISTRY } = await import("../packages/ai/dist/models/index.js");

// Include all modes, exclude external (marketing-only, no API)
const allModels = MODEL_REGISTRY.filter((m) => m.provider !== "external");

function deriveRegions(model) {
    const { provider, modelApiId, id } = model;
    // Direct providers
    if (provider === "google") return ["US", "EU"];
    if (provider === "groq") return ["US"];
    if (provider === "xai") return ["US"];
    if (provider === "fal") return ["US"]; // FAL runs on US infrastructure
    if (provider === "openai") return ["US"];
    if (provider === "klingai") return ["CN", "US"];
    if (provider === "luma") return ["US"];
    if (provider === "replicate") return ["US"];
    if (provider === "fireworks") return ["US"];
    if (provider === "bfl") return ["EU", "US"]; // Black Forest Labs (Germany)

    // OpenRouter/Requesty: derive from underlying model provider
    const apiPrefix = modelApiId.split("/")[0]?.toLowerCase() ?? "";
    const prefixRegionMap = {
        anthropic: ["US", "EU"],
        openai: ["US"],
        google: ["US", "EU"],
        "meta-llama": ["US"],
        mistralai: ["EU", "US"],
        deepseek: ["CN", "US"],
        qwen: ["CN", "US"],
        "alibaba-cloud": ["CN", "US"],
        microsoft: ["US"],
        nvidia: ["US"],
        cohere: ["US", "CA"],
        nousresearch: ["US"],
        moonshotai: ["CN", "US"],
        "perplexity-ai": ["US"],
        bytedance: ["CN", "US"],
    };
    if (prefixRegionMap[apiPrefix]) return prefixRegionMap[apiPrefix];
    if (id.endsWith(":free")) return ["US"];
    return ["US"];
}

function quote(s) { return JSON.stringify(s); }
function formatArray(arr) { return `[${arr.map(quote).join(", ")}]`; }
function formatNumberArray(arr) { return `[${arr.join(", ")}]`; }

const textCount = allModels.filter((m) => !m.mode || m.mode === "text").length;
const imageCount = allModels.filter((m) => m.mode === "image").length;
const videoCount = allModels.filter((m) => m.mode === "video").length;
const sttCount = allModels.filter((m) => m.mode === "speech-to-text").length;
const ttsCount = allModels.filter((m) => m.mode === "text-to-speech").length;

// Build TypeScript output
let ts = `/**
 * Gateway model catalog — single source of truth for ALL models.
 *
 * AUTO-GENERATED by tools/generate-gateway-models.mjs from packages/ai MODEL_REGISTRY.
 * Do NOT edit manually — re-run the generator script when models change:
 *
 *   node tools/generate-gateway-models.mjs
 *
 * Generated: ${new Date().toISOString().split("T")[0]}
 * Total: ${allModels.length} models (${textCount} text, ${imageCount} image, ${videoCount} video, ${sttCount} speech-to-text, ${ttsCount} text-to-speech)
 */

/**
 * Model mode — determines how the model is invoked and what UI is shown.
 */
export type ModelMode = "text" | "image" | "video" | "speech-to-text" | "text-to-speech";

/**
 * Gateway model definition — used for routing, UI catalog, and /v1/models endpoint.
 */
export interface GatewayModelDefinition {
    /** Internal model ID (e.g. "anthropic/claude-sonnet-4") */
    id: string;
    /** Provider key: "openrouter", "groq", "xai", "google", "fal", "openai", etc. */
    provider: string;
    /** Provider-specific API model ID */
    modelApiId: string;
    /** Data-processing regions where this model is hosted (e.g. ["US", "EU"]) */
    regions: string[];
    /** Model mode — "text" (default), "image", "video", "speech-to-text", "text-to-speech" */
    mode: ModelMode;

    // ── UI metadata (optional) ───────────────────────────────────────
    /** Display name for the model picker */
    name?: string;
    /** Short description */
    desc?: string;
    /** Human-readable provider name (e.g. "Anthropic", "Google") */
    displayProvider?: string;
    /** Quality tier for display */
    tier?: "budget" | "fast" | "frontier" | "high-quality" | "medium";
    /** URL slug for marketing pages */
    slug?: string;

    // ── Capabilities (all modes) ─────────────────────────────────────
    /** Whether this model is available (default: true) */
    enabled: boolean;
    /** Supports tool/function calling (text models) */
    supportsTools: boolean;
    /** Supports image/multimodal input (text models) */
    supportsMultimodal: boolean;
    /** Supports file attachments (text models) */
    supportsFileInput: boolean;

    // ── Image/video capabilities ─────────────────────────────────────
    /** Supported aspect ratios (e.g. ["1:1", "16:9"]) */
    aspectRatios?: string[];
    /** Maximum resolution (e.g. "2048x2048") */
    maxResolution?: string;
    /** Average generation latency in ms */
    avgLatencyMs?: number;
    /** Supports negative prompts */
    supportsNegativePrompt?: boolean;
    /** Maximum video duration in seconds */
    maxDuration?: number;
    /** Supports image-to-image transformation */
    supportsImg2Img?: boolean;
    /** Supports image upscaling */
    supportsUpscale?: boolean;
    /** Supports inpainting */
    supportsInpaint?: boolean;
    /** Supports outpainting */
    supportsOutpaint?: boolean;
    /** Supports background removal */
    supportsBackgroundRemoval?: boolean;
    /** Supports object removal */
    supportsObjectRemoval?: boolean;
    /** Available upscale factors (e.g. [2, 4]) */
    upscaleFactors?: number[];
    /** Supports face enhancement in upscaling */
    supportsFaceEnhance?: boolean;
    /** Supports character/subject reference */
    supportsCharacterRef?: boolean;
    /** Character reference modes (e.g. ["face", "style"]) */
    characterRefModes?: string[];
    /** Max number of reference images */
    maxReferenceImages?: number;
    /** Supports style reference/transfer */
    supportsStyleRef?: boolean;
    /** Supports text-to-video generation */
    supportsTextToVideo?: boolean;
    /** Supports image-to-video animation */
    supportsImageToVideo?: boolean;
    /** Maximum video duration in seconds */
    maxVideoDuration?: number;
    /** Supported video FPS options */
    supportedFps?: number[];
    /** Supports ControlNet conditioning */
    supportsControlNet?: boolean;
    /** ControlNet control types */
    controlNetTypes?: string[];
    /** Whether this is a preprocessor model */
    isPreprocessor?: boolean;
    /** Preprocessor type */
    preprocessorType?: string;

    // ── Flags ────────────────────────────────────────────────────────
    /** Requires premium subscription */
    isPremium?: boolean;
    /** Recently added model */
    isNew?: boolean;
    /** Legacy/deprecated model */
    legacy?: boolean;
    /** PostHog feature flag gate */
    featureFlag?: string;
    /** Capability filters (e.g. ["reasoning", "coding", "image_generation"]) */
    filterCapabilities?: string[];
}

/**
 * All model definitions across all modes.
 */
export const GATEWAY_MODELS: GatewayModelDefinition[] = [
`;

for (const m of allModels) {
    const regions = deriveRegions(m);
    const mode = m.mode ?? "text";
    const lines = [];
    lines.push(`    {`);
    lines.push(`        id: ${quote(m.id)},`);
    lines.push(`        provider: ${quote(m.provider)},`);
    lines.push(`        modelApiId: ${quote(m.modelApiId)},`);
    lines.push(`        regions: ${formatArray(regions)},`);
    lines.push(`        mode: ${quote(mode)},`);
    // UI metadata
    if (m.name) lines.push(`        name: ${quote(m.name)},`);
    if (m.desc) lines.push(`        desc: ${quote(m.desc)},`);
    if (m.displayProvider) lines.push(`        displayProvider: ${quote(m.displayProvider)},`);
    if (m.tier) lines.push(`        tier: ${quote(m.tier)},`);
    if (m.slug) lines.push(`        slug: ${quote(m.slug)},`);
    // Core capabilities
    lines.push(`        enabled: ${m.enabled ?? true},`);
    lines.push(`        supportsTools: ${m.supportsToolCalling !== false && mode === "text"},`);
    lines.push(`        supportsMultimodal: ${m.supportsImages === true},`);
    lines.push(`        supportsFileInput: ${m.supportsFileInput === true},`);
    // Image/video capabilities
    if (m.aspectRatios?.length) lines.push(`        aspectRatios: ${formatArray([...m.aspectRatios])},`);
    if (m.maxResolution) lines.push(`        maxResolution: ${quote(m.maxResolution)},`);
    if (m.avgLatencyMs) lines.push(`        avgLatencyMs: ${m.avgLatencyMs},`);
    if (m.supportsNegativePrompt != null) lines.push(`        supportsNegativePrompt: ${m.supportsNegativePrompt},`);
    if (m.maxDuration) lines.push(`        maxDuration: ${m.maxDuration},`);
    if (m.supportsImg2Img) lines.push(`        supportsImg2Img: true,`);
    if (m.supportsUpscale) lines.push(`        supportsUpscale: true,`);
    if (m.supportsInpaint) lines.push(`        supportsInpaint: true,`);
    if (m.supportsOutpaint) lines.push(`        supportsOutpaint: true,`);
    if (m.supportsBackgroundRemoval) lines.push(`        supportsBackgroundRemoval: true,`);
    if (m.supportsObjectRemoval) lines.push(`        supportsObjectRemoval: true,`);
    if (m.upscaleFactors?.length) lines.push(`        upscaleFactors: ${formatNumberArray(m.upscaleFactors)},`);
    if (m.supportsFaceEnhance) lines.push(`        supportsFaceEnhance: true,`);
    if (m.supportsCharacterRef) lines.push(`        supportsCharacterRef: true,`);
    if (m.characterRefModes?.length) lines.push(`        characterRefModes: ${formatArray([...m.characterRefModes])},`);
    if (m.maxReferenceImages) lines.push(`        maxReferenceImages: ${m.maxReferenceImages},`);
    if (m.supportsStyleRef) lines.push(`        supportsStyleRef: true,`);
    if (m.supportsTextToVideo) lines.push(`        supportsTextToVideo: true,`);
    if (m.supportsImageToVideo) lines.push(`        supportsImageToVideo: true,`);
    if (m.maxVideoDuration) lines.push(`        maxVideoDuration: ${m.maxVideoDuration},`);
    if (m.supportedFps?.length) lines.push(`        supportedFps: ${formatNumberArray([...m.supportedFps])},`);
    if (m.supportsControlNet) lines.push(`        supportsControlNet: true,`);
    if (m.controlNetTypes?.length) lines.push(`        controlNetTypes: ${formatArray([...m.controlNetTypes])},`);
    if (m.isPreprocessor) lines.push(`        isPreprocessor: true,`);
    if (m.preprocessorType) lines.push(`        preprocessorType: ${quote(m.preprocessorType)},`);
    // Flags
    if (m.isPremium) lines.push(`        isPremium: true,`);
    if (m.isNew) lines.push(`        isNew: true,`);
    if (m.legacy) lines.push(`        legacy: true,`);
    if (m.featureFlag) lines.push(`        featureFlag: ${quote(m.featureFlag)},`);
    if (m.filterCapabilities?.length) lines.push(`        filterCapabilities: ${formatArray(m.filterCapabilities)},`);
    lines.push(`    },`);
    ts += lines.join("\n") + "\n";
}

ts += `];

/**
 * Map from model ID to gateway model definition.
 */
export const MODEL_MAP = new Map<string, GatewayModelDefinition>(
    GATEWAY_MODELS.map((m) => [m.id, m]),
);

/**
 * Version hash for cache invalidation (changes when model list changes).
 */
export const MODELS_VERSION: string = (() => {
    const ids = GATEWAY_MODELS.map((m) => m.id)
        .toSorted((a, b) => (a < b ? -1 : Number(a > b)))
        .join(",");
    let hash = 5381;
    for (let i = 0; i < ids.length; i++) {
        hash = (hash << 5) + hash + (ids.codePointAt(i) ?? 0);
    }
    return hash.toString(36);
})();
`;

const outPath = resolve(__dirname, "../services/llm-gateway/src/models.generated.ts");
writeFileSync(outPath, ts, "utf-8");
console.log(`✓ Generated ${outPath}`);
console.log(`  ${allModels.length} models total: ${textCount} text, ${imageCount} image, ${videoCount} video, ${sttCount} stt, ${ttsCount} tts`);
