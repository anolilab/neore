/**
 * Lean display entry for marketing pages (footer, /models route, landing page).
 * Derived from MODEL_REGISTRY where listed: true and enabled !== false.
 */
export interface ModelCatalogEntry {
    desc: string;
    mode: "image" | "music" | "text" | "video";
    name: string;
    /** Canonical provider name — must match PROVIDER_ICONS keys in marketing components */
    provider: string;
    slug: string;
    tier: "budget" | "fast" | "frontier" | "high-quality" | "medium";
}

const deriveCatalog = (mode: "text" | "image" | "video" | "music"): ModelCatalogEntry[] =>
    MODEL_REGISTRY.filter((m) => m.listed && m.enabled !== false && (m.mode ?? "text") === mode && m.slug).map((m): ModelCatalogEntry => {
        return {
            desc: m.desc ?? "",
            mode,
            name: m.name ?? m.id,
            provider: m.displayProvider ?? m.provider,
            slug: m.slug as string,
            tier: m.tier ?? "medium",
        };
    });

/** Text models listed on marketing pages (respects enabled flag). */
export const TEXT_CATALOG: ModelCatalogEntry[] = deriveCatalog("text");

/** Image models listed on marketing pages (respects enabled flag). */
export const IMAGE_CATALOG: ModelCatalogEntry[] = deriveCatalog("image");

/** Video models listed on marketing pages (respects enabled flag). */
export const VIDEO_CATALOG: ModelCatalogEntry[] = deriveCatalog("video");

/** Music models listed on marketing pages (respects enabled flag). */
export const MUSIC_CATALOG: ModelCatalogEntry[] = deriveCatalog("music");

/** All listed models combined. */
export const ALL_CATALOG: ModelCatalogEntry[] = [...TEXT_CATALOG, ...IMAGE_CATALOG, ...VIDEO_CATALOG, ...MUSIC_CATALOG];
