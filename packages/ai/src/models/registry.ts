/**
 * O(1) model lookup map for the backend (actions).
 * Keyed by model ID, value is the raw ModelDefinition from MODEL_REGISTRY.
 * Raw ModelDefinition — just the fields the backend needs.
 */
export const MODEL_LOOKUP: ReadonlyMap<string, ModelDefinition> = new Map(
    MODEL_REGISTRY.filter((definition) => definition.provider !== "external").map((definition) => [definition.id, definition]),
);

/**
 * Code-unit comparison, i.e. what `Array#sort()` does by default for strings.
 *
 * `MODELS_VERSION` is a cache key, so the ordering must not drift — a
 * locale-aware comparator would silently change every cached model version.
 */
const compareCodeUnits = (a: string, b: string): number => {
    if (a < b) {
        return -1;
    }

    if (a > b) {
        return 1;
    }

    return 0;
};

/**
 * Version string derived from model IDs for cache invalidation.
 */
export const MODELS_VERSION: string = (() => {
    const modelIds = MODEL_REGISTRY.filter((definition) => definition.provider !== "external")
        .map((m) => m.id)
        .toSorted(compareCodeUnits)
        .join(",");
    let hash = 5381;

    for (const character of modelIds) {
        // DJB2. `Math.imul(hash, 32)` is `hash << 5` without the bitwise
        // operator: both truncate to int32 first, so the digest is unchanged.
        hash = Math.imul(hash, 32) + hash + (character.codePointAt(0) ?? 0);
    }

    return hash.toString(36);
})();

