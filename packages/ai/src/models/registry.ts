// ── FAL provider factory (image / video / transcription / speech) ─────────────
// These helpers use dynamic import so they don't pull @ai-sdk/fal into the
// module-level dependency graph.

/** Create a FAL provider instance, optionally with a user-supplied API key (BYOK). */
export const createFalProvider = async (apiKey?: string) => {
    const { createFal } = await import("@ai-sdk/fal");

    return createFal({ apiKey: apiKey ?? process.env.FAL_API_KEY });
};

