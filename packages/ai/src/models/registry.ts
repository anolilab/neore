// ── Public API ────────────────────────────────────────────────────────────────

export type AgentModel = {
    config: AgentConfig;
    id: string;
};

/**
 * Build agents object from all provider model definitions.
 * - Text models → `chat`
 * - Image models → `imageModel` (fal, openai, xai, google, luma, replicate, fireworks, bfl)
 * - Video models → `videoModel` (fal, klingai, replicate)
 * - FAL transcription models → `transcriptionModel`
 * - FAL speech models → `speechModel`
 * External (marketing-only) models are skipped.
 *
 * Uses dynamic import() for all provider SDKs so this function can be safely
 * imported by backend modules without loading provider code at module-analysis time.
 */
export const buildAgents = async (): Promise<Record<string, AgentConfig>> => {
    const [
        { createGroq },
        { createXai },
        { createOpenRouter },
        { createRequesty },
        { createFal },
        { createOpenAI },
        { createGoogleGenerativeAI },
        { createLuma },
        { createReplicate },
        { createFireworks },
        { createBlackForestLabs },
        { createKlingAI },
    ] = await Promise.all([
        import("@ai-sdk/groq"),
        import("@ai-sdk/xai"),
        import("@openrouter/ai-sdk-provider"),
        import("@requesty/ai-sdk"),
        import("@ai-sdk/fal"),
        import("@ai-sdk/openai"),
        import("@ai-sdk/google"),
        import("@ai-sdk/luma"),
        import("@ai-sdk/replicate"),
        import("@ai-sdk/fireworks"),
        import("@ai-sdk/black-forest-labs"),
        import("@ai-sdk/klingai"),
    ]);

    const headers: Record<string, string> = {};

    if (process.env.SITE_URL) {
        headers["HTTP-Referer"] = process.env.SITE_URL;
    }

    headers["X-Title"] = "neore";

    // Text model factories (providers that primarily serve chat/language models)
    const textProviderFactories: Record<string, (apiKey?: string) => (id: string) => unknown> = {
        groq: (k) => createGroq({ apiKey: k ?? process.env.GROQ_API_KEY }),
        openrouter: (k) => createOpenRouter({ apiKey: k ?? process.env.OPENROUTER_API_KEY, headers }),
        requesty: (k) => createRequesty({ apiKey: k ?? process.env.REQUESTY_API_KEY }),
        xai: (k) => createXai({ apiKey: k ?? process.env.XAI_API_KEY }),
    };

    const fal = createFal({ apiKey: process.env.FAL_API_KEY });
    const openai = createOpenAI({ apiKey: process.env.OPENAI_API_KEY });
    const xai = createXai({ apiKey: process.env.XAI_API_KEY });
    const google = createGoogleGenerativeAI({ apiKey: process.env.GOOGLE_GENERATIVE_AI_API_KEY });
    const luma = createLuma({ apiKey: process.env.LUMA_API_KEY });
    const replicate = createReplicate({ apiToken: process.env.REPLICATE_API_TOKEN });
    const fireworks = createFireworks({ apiKey: process.env.FIREWORKS_API_KEY });
    const bfl = createBlackForestLabs({ apiKey: process.env.BFL_API_KEY });
    const klingai = createKlingAI({ accessKey: process.env.KLINGAI_ACCESS_KEY, secretKey: process.env.KLINGAI_SECRET_KEY });
    const result: Record<string, AgentConfig> = {};

    for (const definition of MODEL_REGISTRY) {
        if (definition.provider === "external") {
            continue; // marketing-only, no API
        }

        // ── FAL: image / video / speech / transcription ─────────────────
        if (definition.provider === "fal") {
            switch (definition.mode) {
                case "music": {
                    // No AI SDK primitive for music — gateway calls FAL via raw HTTP.
                    // Skip agent construction (this entry is gateway-only).
                    break;
                }
                case "speech-to-text": {
                    result[definition.id] = { name: definition.id, transcriptionModel: fal.transcription(definition.modelApiId) };
                    break;
                }
                case "text-to-speech": {
                    result[definition.id] = { name: definition.id, speechModel: fal.speech(definition.modelApiId) };
                    break;
                }
                case "video": {
                    result[definition.id] = { name: definition.id, videoModel: fal.video(definition.modelApiId) };
                    break;
                }
                default: {
                    result[definition.id] = { imageModel: fal.image(definition.modelApiId), name: definition.id };
                }
            }

            continue;
        }

        // ── OpenAI: image models via .image(), video not yet supported ──
        if (definition.provider === "openai") {
            if (definition.mode === "image") {
                result[definition.id] = { imageModel: openai.image(definition.modelApiId), name: definition.id };
            }

            // video mode: skip — @ai-sdk/openai has no .video() method yet
            continue;
        }

        // ── xAI: image models via .image() ──────────────────────────────
        if (definition.provider === "xai" && definition.mode === "image") {
            result[definition.id] = { imageModel: xai.image(definition.modelApiId), name: definition.id };
            continue;
        }

        // ── Google: image models via .image() ───────────────────────────
        if (definition.provider === "google" && definition.mode === "image") {
            result[definition.id] = { imageModel: google.image(definition.modelApiId), name: definition.id };
            continue;
        }

        // ── Luma: image models via .image() ─────────────────────────────
        if (definition.provider === "luma" && definition.mode === "image") {
            result[definition.id] = { imageModel: luma.image(definition.modelApiId), name: definition.id };
            continue;
        }

        // ── Replicate: image/video models via .image()/.video() ─────────
        // `@ai-sdk/replicate` reads its token when a model is CREATED, not when it
        // runs, so without one this loop — every chat's agent build — threw. No
        // token: its models are left out, as an unconfigured provider should be.
        if (definition.provider === "replicate") {
            if (!process.env.REPLICATE_API_TOKEN) {
                continue;
            }

            if (definition.mode === "video") {
                result[definition.id] = { name: definition.id, videoModel: replicate.video(definition.modelApiId) };
            } else if (definition.mode === "image") {
                result[definition.id] = { imageModel: replicate.image(definition.modelApiId), name: definition.id };
            }

            continue;
        }

        // ── Fireworks: image models via .image() ────────────────────────
        if (definition.provider === "fireworks" && definition.mode === "image") {
            result[definition.id] = { imageModel: fireworks.image(definition.modelApiId), name: definition.id };
            continue;
        }

        // ── BFL: image models via .image() ──────────────────────────────
        if (definition.provider === "bfl" && definition.mode === "image") {
            result[definition.id] = { imageModel: bfl.image(definition.modelApiId), name: definition.id };
            continue;
        }

        // ── Kling AI: video models via .video() ────────────────────────
        if (definition.provider === "klingai" && definition.mode === "video") {
            result[definition.id] = { name: definition.id, videoModel: klingai.video(definition.modelApiId) };
            continue;
        }

        // ── Text/chat model factories ───────────────────────────────────
        const factory = textProviderFactories[definition.provider];

        if (!factory) {
            continue;
        }

        const model = factory()(definition.modelApiId) as AgentConfig["chat"];

        if (!model) {
            continue;
        }

        result[definition.id] = {
            chat: model,
            contextOptions: definition.contextOptions,
            instructions: definition.instructions,
            maxRetries: definition.maxRetries,
            maxSteps: definition.maxSteps,
            name: definition.id,
        };
    }

    return result;
};

/**
 * Build a single agent config from a specific model + user API key (BYOK).
 * Accepts either a single API key string or a map of provider → key.
 *
 * Uses dynamic import() for provider SDKs (same reason as buildAgents).
 */
export const buildDynamicAgent = async (modelId: string, apiKey: string | Record<string, string>): Promise<AgentConfig | null> => {
    const definition = MODEL_REGISTRY.find((m) => m.id === modelId);

    if (!definition || definition.provider === "external") {
        return null;
    }

    const resolvedKey = typeof apiKey === "string" ? apiKey : (apiKey[definition.provider] ?? undefined);

    if (definition.provider === "fal") {
        const { createFal } = await import("@ai-sdk/fal");
        const fal = createFal({ apiKey: resolvedKey ?? process.env.FAL_API_KEY });

        switch (definition.mode) {
            case "music": {
                // No AI SDK primitive for music — gateway calls FAL via raw HTTP.
                return null;
            }
            case "speech-to-text": {
                return { name: definition.id, transcriptionModel: fal.transcription(definition.modelApiId) };
            }
            case "text-to-speech": {
                return { name: definition.id, speechModel: fal.speech(definition.modelApiId) };
            }
            case "video": {
                return { name: definition.id, videoModel: fal.video(definition.modelApiId) };
            }
            default: {
                return { imageModel: fal.image(definition.modelApiId), name: definition.id };
            }
        }
    }

    if (definition.provider === "openai") {
        const { createOpenAI } = await import("@ai-sdk/openai");
        const openai = createOpenAI({ apiKey: resolvedKey ?? process.env.OPENAI_API_KEY });

        if (definition.mode === "image") {
            return { imageModel: openai.image(definition.modelApiId), name: definition.id };
        }

        // video mode: skip — @ai-sdk/openai has no .video() method yet
        return null;
    }

    // ── xAI: image models via .image() ──────────────────────────────────
    if (definition.provider === "xai" && definition.mode === "image") {
        const { createXai } = await import("@ai-sdk/xai");

        return { imageModel: createXai({ apiKey: resolvedKey ?? process.env.XAI_API_KEY }).image(definition.modelApiId), name: definition.id };
    }

    // ── Google: image models via .image() ───────────────────────────────
    if (definition.provider === "google" && definition.mode === "image") {
        const { createGoogleGenerativeAI } = await import("@ai-sdk/google");

        return {
            imageModel: createGoogleGenerativeAI({ apiKey: resolvedKey ?? process.env.GOOGLE_GENERATIVE_AI_API_KEY }).image(definition.modelApiId),
            name: definition.id,
        };
    }

    // ── Luma: image models via .image() ─────────────────────────────────
    if (definition.provider === "luma" && definition.mode === "image") {
        const { createLuma } = await import("@ai-sdk/luma");

        return { imageModel: createLuma({ apiKey: resolvedKey ?? process.env.LUMA_API_KEY }).image(definition.modelApiId), name: definition.id };
    }

    // ── Replicate: image/video models via .image()/.video() ────────────
    if (definition.provider === "replicate" && (definition.mode === "image" || definition.mode === "video")) {
        const { createReplicate } = await import("@ai-sdk/replicate");
        const rep = createReplicate({ apiToken: resolvedKey ?? process.env.REPLICATE_API_TOKEN });

        if (definition.mode === "video") {
            return { name: definition.id, videoModel: rep.video(definition.modelApiId) };
        }

        return { imageModel: rep.image(definition.modelApiId), name: definition.id };
    }

    // ── Fireworks: image models via .image() ────────────────────────────
    if (definition.provider === "fireworks" && definition.mode === "image") {
        const { createFireworks } = await import("@ai-sdk/fireworks");

        return { imageModel: createFireworks({ apiKey: resolvedKey ?? process.env.FIREWORKS_API_KEY }).image(definition.modelApiId), name: definition.id };
    }

    // ── BFL: image models via .image() ──────────────────────────────────
    if (definition.provider === "bfl" && definition.mode === "image") {
        const { createBlackForestLabs } = await import("@ai-sdk/black-forest-labs");

        return { imageModel: createBlackForestLabs({ apiKey: resolvedKey ?? process.env.BFL_API_KEY }).image(definition.modelApiId), name: definition.id };
    }

    // ── Kling AI: video models via .video() ─────────────────────────────
    // Kling uses accessKey/secretKey (not a single API key). When `apiKey`
    // is a map, look for "klingai_access_key" and "klingai_secret_key".
    if (definition.provider === "klingai" && definition.mode === "video") {
        const { createKlingAI } = await import("@ai-sdk/klingai");
        const keyMap = typeof apiKey === "string" ? undefined : apiKey;

        return {
            name: definition.id,
            videoModel: createKlingAI({
                accessKey: keyMap?.klingai_access_key ?? process.env.KLINGAI_ACCESS_KEY,
                secretKey: keyMap?.klingai_secret_key ?? process.env.KLINGAI_SECRET_KEY,
            }).video(definition.modelApiId),
        };
    }

    // ── Text/chat model factories ───────────────────────────────────────
    const { createGroq } = await import("@ai-sdk/groq");
    const { createXai } = await import("@ai-sdk/xai");
    const { createOpenRouter } = await import("@openrouter/ai-sdk-provider");
    const { createRequesty } = await import("@requesty/ai-sdk");

    const headers: Record<string, string> = {};

    if (process.env.SITE_URL) {
        headers["HTTP-Referer"] = process.env.SITE_URL;
    }

    headers["X-Title"] = "neore";

    const textProviderFactories: Record<string, (apiKey?: string) => (id: string) => unknown> = {
        groq: (k) => createGroq({ apiKey: k ?? process.env.GROQ_API_KEY }),
        openrouter: (k) => createOpenRouter({ apiKey: k ?? process.env.OPENROUTER_API_KEY, headers }),
        requesty: (k) => createRequesty({ apiKey: k ?? process.env.REQUESTY_API_KEY }),
        xai: (k) => createXai({ apiKey: k ?? process.env.XAI_API_KEY }),
    };

    const factory = textProviderFactories[definition.provider];

    if (!factory) {
        return null;
    }

    const model = factory(resolvedKey)(definition.modelApiId) as AgentConfig["chat"];

    if (!model) {
        return null;
    }

    return {
        chat: model,
        contextOptions: definition.contextOptions,
        instructions: definition.instructions,
        maxRetries: definition.maxRetries,
        maxSteps: definition.maxSteps,
        name: definition.id,
    };
};

